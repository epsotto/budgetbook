import { and, asc, eq, inArray } from 'drizzle-orm';
import type { BookRole } from '$lib/types/Books/budget-book';
import type { Category } from '$lib/types/Settings/category';
import type { Merchant } from '$lib/types/Transactions/merchant';
import { db } from './db';
import { budgetBook, budgetBookMember, budgetTransaction, category, merchant } from './db/schema';

export interface UserBook {
	bookId: string;
	name: string;
	role: BookRole;
}

export type BookMutationResult = 'ok' | 'forbidden' | 'not_found';

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const MAX_NAME_LENGTH = 100;

/** Book ids are UUIDs generated by Postgres (see `budgetBook.id`). */
export function isBookId(value: string): boolean {
	return UUID_PATTERN.test(value);
}

export function validateBookName(value: string): string | null {
	const name = value.trim();
	if (!name) return 'Book name is required.';
	if (name.length > MAX_NAME_LENGTH) {
		return `Book name must be ${MAX_NAME_LENGTH} characters or fewer.`;
	}
	return null;
}

const bookColumns = {
	bookId: budgetBook.id,
	name: budgetBook.name,
	role: budgetBookMember.role
};

export async function listBooksForUser(userId: string): Promise<UserBook[]> {
	return db
		.select(bookColumns)
		.from(budgetBookMember)
		.innerJoin(budgetBook, eq(budgetBookMember.bookId, budgetBook.id))
		.where(eq(budgetBookMember.userId, userId))
		.orderBy(asc(budgetBook.name));
}

export async function getBookForUser(bookId: string, userId: string): Promise<UserBook | null> {
	const [book] = await db
		.select(bookColumns)
		.from(budgetBook)
		.innerJoin(budgetBookMember, eq(budgetBookMember.bookId, budgetBook.id))
		.where(and(eq(budgetBook.id, bookId), eq(budgetBookMember.userId, userId)))
		.limit(1);

	return book ?? null;
}

async function getMembership(bookId: string, userId: string): Promise<BookRole | null> {
	const [membership] = await db
		.select({ role: budgetBookMember.role })
		.from(budgetBookMember)
		.where(and(eq(budgetBookMember.bookId, bookId), eq(budgetBookMember.userId, userId)))
		.limit(1);

	return membership?.role ?? null;
}

/** Creates a book and records the creator as its owner. */
export async function createBook(name: string, userId: string): Promise<UserBook> {
	return db.transaction(async (tx) => {
		const [book] = await tx
			.insert(budgetBook)
			.values({ name, createdBy: userId, updatedBy: userId, updatedAt: new Date() })
			.returning({ id: budgetBook.id });

		await tx.insert(budgetBookMember).values({ bookId: book.id, userId, role: 'owner' });

		return { bookId: book.id, name, role: 'owner' as const };
	});
}

/** Owners and editors can rename a book; viewers cannot. */
export async function renameBook(
	bookId: string,
	name: string,
	userId: string
): Promise<BookMutationResult> {
	const role = await getMembership(bookId, userId);
	if (!role) return 'not_found';
	if (role === 'viewer') return 'forbidden';

	await db
		.update(budgetBook)
		.set({ name, updatedBy: userId, updatedAt: new Date() })
		.where(eq(budgetBook.id, bookId));

	return 'ok';
}

/** Deleting a book is restricted to its owner. Child rows cascade in the database. */
export async function deleteBook(bookId: string, userId: string): Promise<BookMutationResult> {
	const role = await getMembership(bookId, userId);
	if (!role) return 'not_found';
	if (role !== 'owner') return 'forbidden';

	await db.delete(budgetBook).where(eq(budgetBook.id, bookId));

	return 'ok';
}

const CATEGORY_COLORS = [
	'var(--chart-1)',
	'var(--chart-2)',
	'var(--chart-3)',
	'var(--chart-4)',
	'var(--chart-5)'
];

export interface BookDashboardData {
	categories: Category[];
	merchantList: Merchant[];
}

export async function getBookDashboardData(bookId: string): Promise<BookDashboardData> {
	const categories = await db
		.select({
			id: category.id,
			name: category.name,
			icon: category.icon,
			budgetAmount: category.budgetAmount,
			sortOrder: category.sortOrder
		})
		.from(category)
		.where(eq(category.bookId, bookId))
		.orderBy(asc(category.sortOrder), asc(category.name));

	const categoryIds = categories.map((c) => c.id);
	const merchants =
		categoryIds.length === 0
			? []
			: await db
					.select({
						id: merchant.id,
						name: merchant.name,
						categoryId: merchant.categoryId,
						sortOrder: merchant.sortOrder
					})
					.from(merchant)
					.where(inArray(merchant.categoryId, categoryIds))
					.orderBy(asc(merchant.sortOrder), asc(merchant.name));

	const merchantIds = merchants.map((m) => m.id);
	const transactions =
		merchantIds.length === 0
			? []
			: await db
					.select({
						id: budgetTransaction.id,
						itemId: budgetTransaction.itemId,
						amount: budgetTransaction.amount,
						transactionDate: budgetTransaction.transactionDate,
						note: budgetTransaction.note
					})
					.from(budgetTransaction)
					.where(inArray(budgetTransaction.itemId, merchantIds))
					.orderBy(asc(budgetTransaction.transactionDate));

	const transactionsByMerchant = new Map<string, Merchant['transactions']>();
	for (const tx of transactions) {
		const list = transactionsByMerchant.get(tx.itemId) ?? [];
		list.push({
			transactionId: tx.id,
			date: tx.transactionDate,
			amount: parseFloat(tx.amount),
			description: tx.note ?? ''
		});
		transactionsByMerchant.set(tx.itemId, list);
	}

	return {
		categories: categories.map((c, index) => ({
			id: c.id,
			name: c.name,
			icon: c.icon ?? 'shopping-cart',
			iconColor: CATEGORY_COLORS[index % CATEGORY_COLORS.length],
			budget: parseFloat(c.budgetAmount)
		})),
		merchantList: merchants.map((m) => ({
			id: m.id,
			name: m.name,
			categoryId: m.categoryId,
			transactions: transactionsByMerchant.get(m.id) ?? []
		}))
	};
}
